const SMARK = '[°゜ﾟ˚º゚○◦]'; // 半濁点が化けた記号

// 偏と旁に割れて読まれた漢字(「計」→「言十」など)。レシートの定番語だけ
const SPLIT = [['言十', '計'], ['禾兌', '税'], ['客頁', '額'], ['客真', '額'], ['金勺', '釣'], ['予頁', '預'], ['令頁', '領'], ['貝占', '貼'], ['口乙', '吃']].filter((x) => x[1] !== '吃' && x[1] !== '貼');
// カタカナと形が同じ漢字・数字(両隣がカタカナのときだけ置き換える)
const LOOK = { 口: 'ロ', 工: 'エ', 二: 'ニ', 八: 'ハ', 力: 'カ', 卜: 'ト', 夕: 'タ', 1: 'イ', '|': 'ー', '丨': 'ー' };

export function fixName(s) {
  let t = String(s ?? '');
  t = Array.from(t, (c) => SMAP.get(c) ?? c).join('');
  for (const [a, b] of SPLIT) t = t.split(a).join(b);
  t = t.replace(new RegExp(`([カ-コサ-ソタ-トハ-ホウか-こさ-そた-とは-ほ])(?:${VMARK})`, 'g'), (m, c) => VOICE[c] || m);
  t = t.replace(new RegExp(`([ハ-ホは-ほ])(?:${SMARK})`, 'g'), (m, c) => SEMI[c] || m);
  t = t.replace(new RegExp(`([ガ-ゴザ-ゾダ-ドバ-ボパ-ポヴが-ござ-ぞだ-どば-ぼぱ-ぽ])(?:${VMARK}|${SMARK})+`, 'g'), '$1'); // すでに濁点・半濁点つきの字の後ろに残った余計な記号
  // 半濁点が「・」「。」に化けた(「フ・ラ」→「プラ」)。すでに半濁点つきの字(「プ・ラ」)の後ろの「・」は余計なのでとる
  t = t.replace(/([ハヒフヘホ])[・。](?=[ァ-ヶー])/g, (m, c) => SEMI[c]);
  t = t.replace(/(?<=[パピプペポ])[・。](?=[ァ-ヶー])/g, '');
  // 長音: カタカナに挟まれる/続く「一」「ー」風の字(一・—・－・‐・-)は「ー」
  t = t.replace(/([ァ-ヶ])[一—－‐―─]+(?=[ァ-ヶー]|\s|$|\d)/g, '$1ー');
  t = t.replace(/(?<=[ァ-ヶ])(?<![ンッ])[一—－‐―─-](?=[ァ-ヶ])/g, 'ー'); // (「ン」「ッ」の後ろに長音は来ないので、「セブン-イレブン」のハイフンは残す)
  t = t.replace(/(?<=[ァ-ヶー])([口工二八力卜夕1|丨])(?=[ァ-ヶー])/g, (m, c) => LOOK[c]); // 「ラ1ス」→「ライス」「ミ二トマト」→「ミニトマト」
  t = t.replace(/([口工二八力卜夕])(?=ー)/g, (m, c) => LOOK[c]); // 「牛乳口ール」(長音が続けば左がカナでなくてもカナ)
  t = t.replace(/(?<=\d)[〇Ｏ]+|(?<=^|\s)[〇Ｏ]+(?=\d)/g, (m) => '0'.repeat(m.length)); // 「1〇〇〇」
  return t;
}

// OCR全体の行ごとの補正(品名だけでなく行全体に使う。金額や記号は触らない)
export function fixLine(s) { return fixName(s); }
