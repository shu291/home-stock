for (const [text, date, kind, o = {}] of CASES) {
  t(`parse: ${JSON.stringify(text)}`, () => {
    const r = parseExpiry(text, { today: o.today || TODAY, boughtAt: o.boughtAt });
    assert.equal(r.best ? r.best.date : null, date, JSON.stringify(r.candidates));
    if (date) assert.equal(r.best.kind, kind);
  });
}

// ---- 2. 返り値の形・補助情報 ----
t('返り値の形', () => {
  const r = parseExpiry('賞味期限 2026.11.05', { today: TODAY });
  assert.deepEqual(Object.keys(r.candidates[0]).sort(), ['conf', 'date', 'kind', 'label', 'raw']);
  assert.equal(r.best, r.candidates[0]);
  assert.ok(r.best.conf >= BEST_MIN && r.best.conf <= 1);
});
t('月末扱いは label に書く', () => assert.match(parseExpiry('賞味期限 2027.02', { today: TODAY }).best.label, /月末扱い/));
t('年を補った旨は label に書く', () => assert.match(parseExpiry('消費期限 11/05', { today: TODAY }).best.label, /年を補った/));
t('製造日は mfg に入り、期限にはならない', () => {
  const r = parseExpiry('製造日 2026.10.20 賞味期限 2027.04.19', { today: TODAY });
  assert.deepEqual(r.mfg.map((m) => m.date), ['2026-10-20']);
  assert.ok(!r.candidates.some((c) => c.date === '2026-10-20'));
});
t('製造日だけなら答えない', () => { const r = parseExpiry('製造日 2026.10.25', { today: TODAY }); assert.equal(r.best, null); assert.equal(r.candidates.length, 0); });
t('開封後の目安は opened に入り、期限にならない', () => {
  const r = parseExpiry('賞味期限 2027.01.10 開封後は冷蔵庫で5日以内にお召し上がりください', { today: TODAY });
  assert.equal(r.best.date, '2027-01-10'); assert.deepEqual(r.opened.map((o) => o.days), [5]);
});
t('枠外下部に記載 → note', () => { const r = parseExpiry('賞味期限 枠外下部に記載', { today: TODAY }); assert.equal(r.best, null); assert.ok(r.note); });
t('日付が見つかれば note は空', () => assert.equal(parseExpiry('賞味期限 2027.01.10', { today: TODAY }).note, ''));
t('today 省略でも動く(実際の今日)', () => { const r = parseExpiry('賞味期限 2099.01.01'); assert.ok(r.candidates.length === 0 || r.best === null); });
t('ラベルなし・年なしの日付は答えない', () => assert.equal(parseExpiry('11/05', { today: TODAY }).best, null));
t('電話番号・JAN・時刻は日付にしない', () => assert.equal(parseExpiry('TEL 03-1234-5678 4901234567894 12:30 ¥198 10℃以下', { today: TODAY }).candidates.length, 0));
t('ラベルに近い日付を優先(製造日が後でも)', () => assert.equal(parseExpiry('賞味期限 2026.12.01 製造日 2026.12.20', { today: TODAY }).best.date, '2026-12-01'));
t('boughtAt より前の日付は確信を下げる', () => assert.equal(parseExpiry('賞味期限 2026.10.01', { today: TODAY, boughtAt: '2026-10-20' }).best, null));
t('10年以上先は答えない', () => assert.equal(parseExpiry('賞味期限 2041.11.05', { today: TODAY }).best, null));
t('Date オブジェクトの today も受ける', () => assert.equal(parseExpiry('消費期限 11/05', { today: new Date(2026, 9, 28) }).best.date, '2026-11-05'));

// ---- 3. 複数の読みの統合(combineExpiry) ----
t('同じ日付が複数の読みで出ると確信が上がる', () => {
  const a = parseExpiry('賞味期限 2027.01.10', { today: TODAY }), b = parseExpiry('2027.01.10', { today: TODAY });
  const one = combineExpiry([a]), two = combineExpiry([a, b]);
  assert.equal(two.best.date, '2027-01-10'); assert.ok(two.best.conf > one.best.conf); assert.equal(two.best.kind, '賞味');
});
