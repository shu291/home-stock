const SIM = new Map();
GROUPS.forEach((g, gi) => { for (const c of g) { const a = SIM.get(c) || new Set(); a.add(gi); SIM.set(c, a); } });
const close = (a, b) => { const x = SIM.get(a), y = SIM.get(b); if (!x || !y) return false; for (const g of x) if (y.has(g)) return true; return false; };
const SOFT = new Set(['ー', '・', '゛', '゜', '.', '°', '`', "'"]); // 抜けたり増えたりしやすい記号(安い)

const extra = new Set();
export function setVocabulary(list) { extra.clear(); for (const w of list || []) { const t = String(w).normalize('NFKC').trim(); if (t.length >= 3) extra.add(t); } }

// text の中で語 v に近い部分(近似部分一致)を探す。{cost, s, e}(text[s,e) が該当)。コストは小さいほどよく合う
function approx(t, v) {
  const n = t.length, m = v.length;
  let prev = new Float64Array(n + 1), prevS = new Int32Array(n + 1);
  for (let j = 0; j <= n; j++) prevS[j] = j; // 先頭は自由(どこから始まってもよい)
  for (let i = 1; i <= m; i++) {
    const cur = new Float64Array(n + 1), curS = new Int32Array(n + 1);
    cur[0] = prev[0] + (SOFT.has(v[i - 1]) ? 0.5 : 1); curS[0] = 0;
    for (let j = 1; j <= n; j++) {
      const a = v[i - 1], b = t[j - 1];
      const sub = prev[j - 1] + (a === b ? 0 : close(a, b) ? 0.3 : 1);
      const del = prev[j] + (SOFT.has(a) ? 0.5 : 1); // 語の字が文字列に無い
      const ins = cur[j - 1] + (SOFT.has(b) ? 0.5 : 1); // 文字列に余計な字がある
      if (sub <= del && sub <= ins) { cur[j] = sub; curS[j] = prevS[j - 1]; } else if (del <= ins) { cur[j] = del; curS[j] = prevS[j]; } else { cur[j] = ins; curS[j] = curS[j - 1]; }
    }
    prev = cur; prevS = curS;
  }
  let bj = 0; for (let j = 1; j <= n; j++) if (prev[j] < prev[bj] || (prev[j] === prev[bj] && j - prevS[j] > bj - prevS[bj])) bj = j;
  return { cost: prev[bj], s: prevS[bj], e: bj };
}

// 語の長さに応じた許容コスト。短い語は「似た字の取り違え1つ」まで、5〜7字は2つまで、8字以上は別の字への置換や欠落も1つまで許す
const limit = (len) => (len <= 4 ? 0.35 : len <= 7 ? 0.65 : 1.3);
// 字種(ひらがな/カタカナ/漢字/その他)。短い語は、同じ字種の連なり(語の切れ目が字種の変わり目)に完全に重なるときだけ直す
const cls = (c) => (c === undefined ? 'x' : /[ぁ-ゖ]/.test(c) ? 'h' : /[ァ-ヺー・]/.test(c) ? 'k' : /[一-龠々]/.test(c) ? 'j' : 'o');
const bounded = (t, s, e) => cls(t[s - 1]) !== cls(t[s]) && cls(t[e]) !== cls(t[e - 1]);

// 1行(または品名)の文字列を語彙で直す。語彙に近い部分だけを置き換え、ほかは触らない
export function correctText(text, extraWords) {
  const t = Array.from(String(text ?? ''));
  if (t.length < 3) return String(text ?? '');
  const words = extraWords ? WORDS.concat(extraWords) : extra.size ? WORDS.concat([...extra]) : WORDS;
  const cands = [];
  for (const w of words) {
    const v = Array.from(w), lim = limit(v.length);
    if (t.length + 2 < v.length) continue; // 文字列が語より大幅に短ければ無理
    const r = approx(t, v);
    if (r.cost > lim || r.e - r.s < Math.max(2, v.length - 2)) continue;
    // 3〜4字の語は、字種の切れ目に重なるときだけ直す。ただし4字で「同じ長さで、似た字の取り違えだけ」なら、カナの連なりの途中でも直す
    const sameLen = v.length === 4 && r.e - r.s === 4 && v.every((c, i) => c === t[r.s + i] || close(c, t[r.s + i]));
    if (v.length > 4 || sameLen || bounded(t, r.s, r.e)) cands.push({ ...r, w, len: v.length });
  }
  // コストの低い順(同じなら長い語)に、重ならないものだけ採用。完全一致(コスト0)の範囲は守られる
  cands.sort((a, b) => a.cost - b.cost || b.len - a.len);
  const used = [], pick = [];
  for (const c of cands) {
    if (used.some((u) => c.s < u.e && u.s < c.e)) continue;
    used.push(c); if (c.cost > 0) pick.push(c);
  }
  pick.sort((a, b) => b.s - a.s);
  for (const c of pick) t.splice(c.s, c.e - c.s, ...Array.from(c.w));
  return t.join('');
}

