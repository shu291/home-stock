// 学習用(辞書づくりで見る)と検証用(見ない)に分ける。index%3===2 が検証用
export const TRAIN = EVAL.filter((_, i) => i % 3 !== 2);
export const VALID = EVAL.filter((_, i) => i % 3 === 2);

// guess(name) → {category, sub}。指標: acc=正解率(全件) prec=答えた中の適合率 blank=空の率(分母は正解が空でない件)
export function evaluate(guess, items) {
  const r = { n: items.length, cat: { ok: 0, ans: 0, okAns: 0, blank: 0, den: 0 }, sub: { ok: 0, ans: 0, okAns: 0, blank: 0, den: 0 }, wrong: [] };
  for (const it of items) {
    const g = guess(it.name);
    const cOk = g.category === it.category, sOk = cOk && g.sub === it.sub;
    if (cOk) r.cat.ok++; if (sOk) r.sub.ok++;
    if (g.category) { r.cat.ans++; if (cOk) r.cat.okAns++; }
    if (g.sub) { r.sub.ans++; if (sOk) r.sub.okAns++; }
    if (it.category) { r.cat.den++; if (!g.category) r.cat.blank++; }
    if (it.sub) { r.sub.den++; if (!g.sub) r.sub.blank++; }
    if (!sOk && (g.category || g.sub)) r.wrong.push(`${it.name} 期待[${it.category}/${it.sub}] 結果[${g.category}/${g.sub}]`);
  }
  const p = (a, b) => (b ? a / b : 1);
  return { n: r.n, wrong: r.wrong, catAcc: p(r.cat.ok, r.n), catPrec: p(r.cat.okAns, r.cat.ans), catBlank: p(r.cat.blank, r.cat.den), subAcc: p(r.sub.ok, r.n), subPrec: p(r.sub.okAns, r.sub.ans), subBlank: p(r.sub.blank, r.sub.den) };
}
